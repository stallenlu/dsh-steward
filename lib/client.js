    // 它自己读一次设置 + 一次报告，此后靠 publishReport 被动更新。
    function ToastHost(props) {
      const [, force] = React.useState(0);
      React.useEffect(() => {
        const fn = () => force((v) => v + 1);
        toastListeners.add(fn);
        return () => { toastListeners.delete(fn); };
      }, []);
      React.useEffect(() => {
        let alive = true;
        const onReport = (report) => {
          if (!alive) return;
          try { evaluateToasts(report); } catch { /* noop */ }
        };
        reportListeners.add(onReport);
        void (async () => {
          try {
            const res = await call('settings');
            const ui = res && res.settings && res.settings.ui ? res.settings.ui : null;
            if (ui && (ui.toast === 'critical' || ui.toast === 'warning' || ui.toast === 'off')) toastConfig.mode = ui.toast;
            if (ui && Number.isFinite(ui.toastSeconds)) toastConfig.seconds = ui.toastSeconds;
          } catch { /* 读不到设置就用默认：只弹严重、12 秒 */ }
          // 面板已经体检过就直接复用，不为弹窗再跑一次全量采集。
          if (alive && cache.report) { try { evaluateToasts(cache.report); } catch { /* noop */ } return; }
          // 面板没开（用户没点开管家）时，弹窗仍然要能提醒——这正是它存在的理由。
          // 只在挂载后取一次，不做轮询：提醒的及时性来自「页面打开时立刻看一遍」，
          // 而不是把体检变成后台常驻任务。
          if (!alive || toastConfig.mode === 'off') return;
          try {
            const data = await call('report');
            if (!alive) return;
            if (data && typeof data.autoScanMinutes === 'number') cache.autoScanMinutes = data.autoScanMinutes;
            if (data && data.wiring) cache.wiring = data.wiring;
            if (data && data.duty) cache.duty = data.duty;
            if (data && data.report) { cache.report = data.report; evaluateToasts(data.report); }
          } catch { /* 采集失败不弹任何东西——宁可不提醒，也不误报 */ }
        })();
        return () => { alive = false; reportListeners.delete(onReport); };
      }, []);
      const items = toastStore.items;
      if (!items.length) return null;
      return h('div', {
        style: {
          position: 'fixed', right: 18, bottom: 18, zIndex: 1200,
          display: 'flex', flexDirection: 'column', gap: 10, alignItems: 'flex-end',
          maxWidth: 'min(360px, calc(100vw - 36px))',
        },
      }, items.map((t) => h(ToastCard, {
        key: t.id, toast: t, seconds: toastConfig.seconds,
        onDismiss: () => dismissToast(t.id),
        onOpen: () => { try { if (props && props.onOpen) props.onOpen(t.actionKey); } catch { /* noop */ } },
        onAck: () => { try { if (props && props.onAck) props.onAck(t.findingId); } catch { /* noop */ } },
      })));
    }

